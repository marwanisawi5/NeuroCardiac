"""# Helper Functions

To improve the organization and readability of the notebook, reusable helper functions are defined before they are used.

## Create Dataset DataFrame

The MRI images are organized into folders, where each folder represents a different class.

The following function scans the dataset directory, reads every image file, and creates a **Pandas DataFrame** containing:

- **File Path:** The complete path to each image.
- **Label:** The class name extracted from the parent folder.
"""

def create_dataframe_from_paths(base_dir):
    classes = []
    class_paths = []

    for class_name in os.listdir(base_dir):
        class_path_full = os.path.join(base_dir, class_name)
        if os.path.isdir(class_path_full):
            for img_name in os.listdir(class_path_full):
                if img_name.endswith(('.jpg', '.jpeg', '.png')):
                    classes.append(class_name)
                    class_paths.append(os.path.join(class_path_full, img_name))

    df = pd.DataFrame({'Class Path': class_paths, 'Class': classes})
    return df

"""## Generate Dataset Information

Before training the model, it is useful to understand the composition of the dataset.

The following function summarizes important information such as:

- Total number of images.
- Number of images in each class.
- Class distribution.
"""

def get_dataset_info(base_dir):
    total_images = 0
    class_counts = defaultdict(int)
    all_image_paths = []

    for class_name in os.listdir(base_dir):
        class_path = os.path.join(base_dir, class_name)
        if os.path.isdir(class_path):
            for img_name in os.listdir(class_path):
                if img_name.endswith(('.jpg', '.jpeg', '.png')):
                    all_image_paths.append(os.path.join(class_path, img_name))
                    class_counts[class_name] += 1
                    total_images += 1
    return total_images, class_counts, all_image_paths

