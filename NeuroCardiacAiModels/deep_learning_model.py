"""## Image Preprocessing and Data Augmentation

The `ImageDataGenerator` is used to prepare the images before they are passed to the CNN.

For the **training dataset**, data augmentation is applied by introducing random transformations such as rotations, shifts, zooming, and horizontal flipping. These transformations generate new variations of the existing images, increasing the diversity of the training data without collecting additional MRI scans.

In addition, pixel values are normalized by scaling them to the range **0–1**, allowing the CNN to train more efficiently.

For the **validation** and **testing** datasets, only normalization is applied so that the model is evaluated using the original images without artificial modifications.
"""

batch_size = 32
img_size = (299, 299)

_gen = ImageDataGenerator(rescale=1/255,
                          brightness_range=(0.8, 1.2))

ts_gen = ImageDataGenerator(rescale=1/255)


tr_gen = _gen.flow_from_dataframe(train_df, x_col='Class Path',
                                  y_col='Class', batch_size=batch_size,
                                  target_size=img_size)

valid_gen = _gen.flow_from_dataframe(valid_df, x_col='Class Path',
                                     y_col='Class', batch_size=batch_size,
                                     target_size=img_size)

ts_gen = ts_gen.flow_from_dataframe(test_df, x_col='Class Path',
                                  y_col='Class', batch_size=16,
                                  target_size=img_size, shuffle=False)

