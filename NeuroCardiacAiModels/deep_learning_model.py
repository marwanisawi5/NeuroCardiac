"""# CNN Model Architecture

A **Convolutional Neural Network (CNN)** is designed specifically for image classification tasks. Unlike traditional machine learning algorithms, CNNs automatically learn important features directly from images, such as edges, shapes, textures, and complex patterns.

In this project, a custom CNN architecture is developed to classify brain MRI images into four categories. The model consists of convolutional layers for feature extraction, pooling layers for dimensionality reduction, normalization and dropout layers to improve generalization, and fully connected layers for final classification.

## Build the CNN Model

The following code defines the architecture of the Convolutional Neural Network.

The model is built sequentially, where each layer performs a specific task:

- **Convolutional Layers (Conv2D):** Extract visual features from the MRI images.
- **Batch Normalization:** Stabilizes and accelerates the learning process.
- **Max Pooling Layers:** Reduce the spatial dimensions while preserving important features.
- **Dropout Layers:** Randomly deactivate neurons during training to reduce overfitting.
- **Dense Layers:** Combine the extracted features to perform classification.
- **Output Layer:** Produces the probability for each brain tumor class using the Softmax activation function.
"""

num_classes = len(tr_gen.class_indices);

input_shape = img_size + (3,)

model = Sequential([
    Input(shape=input_shape), # Explicitly define the input layer
    Conv2D(32, (3, 3), activation='relu'),
    MaxPooling2D((2, 2)),
    Conv2D(64, (3, 3), activation='relu'), # Restored this layer
    MaxPooling2D((2, 2)), # Restored this layer
    Conv2D(128, (3, 3), activation='relu'),
    MaxPooling2D((2, 2)),
    Flatten(),
    Dense(128, activation='relu'),
    Dropout(0.5),
    Dense(num_classes, activation='softmax')
])

"""## Compile the Model

After defining the network architecture, the model is compiled.

During compilation, three important components are specified:

- **Optimizer:** Determines how the model updates its weights during training.
- **Loss Function:** Measures the difference between the predicted and actual class labels.
- **Evaluation Metric:** Tracks the model's performance during training and validation.
"""

model.compile(optimizer='adam',
              loss='categorical_crossentropy',
              metrics=['accuracy'])

"""## Model Summary

The model summary provides an overview of the network architecture, including the output shape of each layer and the number of trainable parameters.
"""

model.summary()

"""# Model Training

After defining and compiling the CNN architecture, the model is trained using the prepared training dataset.

## Train the CNN Model

The `model.fit()` function starts the training process by repeatedly passing batches of images through the network.

During each epoch, the following steps are performed:

1. A batch of training images is processed.
2. Predictions are generated.
3. The loss is calculated by comparing the predictions with the true labels.
4. The optimizer updates the model's weights to reduce the prediction error.
5. The model is evaluated using the validation dataset to monitor its performance on unseen data.
"""

